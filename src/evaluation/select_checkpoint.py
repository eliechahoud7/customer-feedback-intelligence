"""Choose the best fine-tuning checkpoint on the validation split.

Every ``checkpoint-<step>`` directory of a training run is evaluated on the
validation split with the project's metrics, and the checkpoint with the
highest aspect + sentiment F1 is selected. Ties go to the higher aspect F1,
then to the earlier checkpoint. Missing predictions or invalid metrics stop the
selection instead of being skipped.

The selection split is fixed to validation: the test split is never read,
generated or scored here. Predictions are generated by running
src.modeling.inference in a separate process per checkpoint (so GPU memory is
freed between checkpoints); existing prediction files are reused unless
--regenerate is given. The report records file checksums and contains no
timestamps, so the same predictions always produce the same report.

Usage (Colab):
    python -m src.evaluation.select_checkpoint --run-dir outputs/qwen2.5-3b-absa-qlora
    python -m src.evaluation.select_checkpoint --run-dir outputs/qwen2.5-3b-absa-qlora --score-only
"""

from __future__ import annotations

import argparse
import json
import math
import re
import subprocess
import sys
from pathlib import Path

from src.data.build_sft_dataset import file_sha256, load_jsonl
from src.data.prepare_dataset import DEFAULT_CONFIG, PROJECT_ROOT, load_config
from src.data.prompts import PROMPT_VERSION
from src.evaluation.metrics import load_responses, score_reviews, summarize
from src.modeling.train import git_commit

SELECTION_SPLIT = "validation"
CHECKPOINT_PATTERN = re.compile(r"^checkpoint-(\d+)$")
CRITERION = ("aspect_sentiment", "f1")
TIE_BREAK = ["aspect.f1 (higher)", "step (earlier)"]
# Metrics every candidate must report as finite numbers in [0, 1].
REQUIRED_METRICS = (
    ("aspect_sentiment", "f1"),
    ("aspect", "f1"),
    ("sentiment", "macro_f1"),
    ("sentiment_without_conflict", "macro_f1"),
)


def find_checkpoints(run_dir: Path) -> list[tuple[int, Path]]:
    """checkpoint-<step> directories, sorted by step; each must hold an adapter."""
    if not run_dir.is_dir():
        raise FileNotFoundError(f"training run directory not found: {run_dir}")
    checkpoints = []
    for path in run_dir.iterdir():
        match = CHECKPOINT_PATTERN.match(path.name)
        if match and path.is_dir():
            if not (path / "adapter_config.json").is_file():
                raise FileNotFoundError(f"{path} has no adapter_config.json")
            checkpoints.append((int(match.group(1)), path))
    if not checkpoints:
        raise FileNotFoundError(f"no checkpoint-<step> directories in {run_dir}")
    return sorted(checkpoints)


def base_model_of(checkpoint: Path) -> str:
    with (checkpoint / "adapter_config.json").open(encoding="utf-8") as f:
        return json.load(f)["base_model_name_or_path"]


def predictions_path(eval_dir: Path, checkpoint: Path) -> Path:
    return eval_dir / f"{checkpoint.name}_{SELECTION_SPLIT}.jsonl"


def inference_command(checkpoint: Path, output: Path, batch_size: int, max_new_tokens: int) -> list[str]:
    return [
        sys.executable, "-m", "src.modeling.inference",
        "--split", SELECTION_SPLIT,
        "--model", base_model_of(checkpoint),
        "--adapter", str(checkpoint),
        "--output", str(output),
        "--batch-size", str(batch_size),
        "--max-new-tokens", str(max_new_tokens),
    ]


def run_inference(command: list[str]) -> None:
    subprocess.run(command, cwd=PROJECT_ROOT, check=True)


def metric(summary: dict, path: tuple[str, str]):
    return summary[path[0]][path[1]]


def validate_metrics(summary: dict, checkpoint: str) -> None:
    for path in REQUIRED_METRICS:
        name = ".".join(path)
        try:
            value = metric(summary, path)
        except (KeyError, TypeError):
            raise ValueError(f"{checkpoint}: metric {name} is missing") from None
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise ValueError(f"{checkpoint}: metric {name} is not a number: {value!r}")
        if not math.isfinite(value) or not 0 <= value <= 1:
            raise ValueError(f"{checkpoint}: metric {name} is outside [0, 1]: {value!r}")


def select(candidates: list[dict]) -> dict:
    """Highest aspect+sentiment F1; ties to higher aspect F1, then the earlier step."""
    if not candidates:
        raise ValueError("no candidates to select from")
    for candidate in candidates:
        validate_metrics(candidate["metrics"], candidate["checkpoint"])
    return min(
        candidates,
        key=lambda c: (-metric(c["metrics"], CRITERION), -metric(c["metrics"], ("aspect", "f1")), c["step"]),
    )


def evaluate_checkpoints(
    run_dir: Path,
    eval_dir: Path,
    records: list[dict],
    generate: bool = True,
    regenerate: bool = False,
    runner=run_inference,
    batch_size: int = 8,
    max_new_tokens: int = 256,
) -> list[dict]:
    checkpoints = find_checkpoints(run_dir)

    if not generate:
        missing = [path.name for _, path in checkpoints if not predictions_path(eval_dir, path).is_file()]
        if missing:
            raise FileNotFoundError(f"no {SELECTION_SPLIT} predictions for {missing}; run without --score-only")

    candidates = []
    for step, path in checkpoints:
        predictions = predictions_path(eval_dir, path)
        if generate and (regenerate or not predictions.is_file()):
            runner(inference_command(path, predictions, batch_size, max_new_tokens))
            if not predictions.is_file():
                raise FileNotFoundError(f"inference for {path.name} did not write {predictions}")

        # score_reviews requires exactly one response per validation review, so
        # predictions for any other split are rejected here.
        summary = summarize(score_reviews(records, load_responses(predictions)))
        candidates.append(
            {
                "checkpoint": path.name,
                "step": step,
                "path": _display(path),
                "predictions": _display(predictions),
                "predictions_sha256": file_sha256(predictions),
                "metrics": summary,
            }
        )
    return candidates


def run_selection(
    run_dir: Path,
    eval_dir: Path,
    splits_dir: Path,
    output: Path,
    generate: bool = True,
    regenerate: bool = False,
    runner=run_inference,
    batch_size: int = 8,
    max_new_tokens: int = 256,
) -> dict:
    validation_path = splits_dir / f"{SELECTION_SPLIT}.jsonl"
    records = load_jsonl(validation_path)
    candidates = evaluate_checkpoints(
        run_dir, eval_dir, records, generate, regenerate, runner, batch_size, max_new_tokens
    )
    selected = select(candidates)

    report = {
        "split": SELECTION_SPLIT,
        "criterion": ".".join(CRITERION),
        "tie_break": TIE_BREAK,
        "selected": {
            "checkpoint": selected["checkpoint"],
            "step": selected["step"],
            "path": selected["path"],
            "metrics": {".".join(path): metric(selected["metrics"], path) for path in REQUIRED_METRICS},
        },
        "candidates": candidates,
        "validation_split_sha256": file_sha256(validation_path),
        "prompt_version": PROMPT_VERSION,
        "git": git_commit(),
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="\n") as f:
        json.dump(report, f, indent=2)
        f.write("\n")
    return report


def _display(path: Path) -> str:
    """Project-relative path where possible, so reports are portable."""
    try:
        return path.resolve().relative_to(PROJECT_ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run-dir", type=Path, required=True, help="training output_dir with checkpoint-<step>/")
    parser.add_argument("--eval-dir", type=Path, default=Path("outputs/eval"))
    parser.add_argument("--output", type=Path, help="default: <eval-dir>/checkpoint_selection.json")
    parser.add_argument("--score-only", action="store_true", help="never run inference; require saved predictions")
    parser.add_argument("--regenerate", action="store_true", help="re-run inference even if predictions exist")
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--max-new-tokens", type=int, default=256)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    args = parser.parse_args()
    if args.score_only and args.regenerate:
        parser.error("--score-only and --regenerate cannot be combined")

    resolve = lambda p: p if p.is_absolute() else PROJECT_ROOT / p  # noqa: E731
    eval_dir = resolve(args.eval_dir)
    output = resolve(args.output) if args.output else eval_dir / "checkpoint_selection.json"
    report = run_selection(
        run_dir=resolve(args.run_dir),
        eval_dir=eval_dir,
        splits_dir=PROJECT_ROOT / load_config(args.config)["output"]["splits_dir"],
        output=output,
        generate=not args.score_only,
        regenerate=args.regenerate,
        batch_size=args.batch_size,
        max_new_tokens=args.max_new_tokens,
    )

    print(f"{'checkpoint':20s} {'pair F1':>8s} {'aspect F1':>10s} {'macro F1':>9s} {'invalid JSON':>13s}")
    for c in report["candidates"]:
        m = c["metrics"]
        print(f"{c['checkpoint']:20s} {m['aspect_sentiment']['f1']:8.4f} {m['aspect']['f1']:10.4f} "
              f"{m['sentiment']['macro_f1']:9.4f} {m['responses']['invalid_json']:13d}")
    print(f"\nselected: {report['selected']['checkpoint']} ({report['selected']['path']})")
    print(f"report:   {_display(output)}")


if __name__ == "__main__":
    main()
